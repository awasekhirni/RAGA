"""Tool-spec factory: turns registry contracts into provider tool payloads.

Security role
-------------
The spec's Strategy 1 proposes ``exec``-ing schema strings from the
registry.  This implementation deliberately does **not** execute registry
strings: the typed classes in :mod:`case_engine.schemas.mental_models`
are the single source of truth, and their JSON Schemas are generated by
Pydantic itself.  Benefits (documented in docs/ARCHITECTURE.md §1.2):

* no arbitrary-code execution surface (registry data can never become
  code, even if the registry is tampered with),
* contract and JSON schema can never drift (generated from the class),
* provider serialization is deterministic and testable.

Because the specs handed to providers are derived from the very same
classes the :class:`~case_engine.enforcement.gate.SchemaGate` enforces,
"what the provider may emit" and "what the gate accepts" cannot diverge.

Contents
--------
- :class:`ToolFactory` -- ``openai_tool`` / ``anthropic_tool`` /
  ``generic_tool`` spec builders plus ``json_schema`` introspection.

Invariants
----------
- The factory never ``exec()``s, ``eval()``s or dynamically imports
  anything; a registry entry whose ``schema_class`` does not resolve to
  the registered contract is a hard
  :class:`~case_engine.exceptions.RegistryError` (fail-fast).
- Generated specs are pure JSON-serializable data, safe to embed in
  provider requests and pipeline state (``CASEState.tool_specs``).

Cross-references: docs/ARCHITECTURE.md §1.2, docs/EXTENDING.md (adding
a mental model), docs/VALIDATION_RULES.md (what the emitted specs are
later held accountable for).
"""

from __future__ import annotations

from typing import Any

from case_engine.exceptions import RegistryError
from case_engine.logging_setup import get_logger
from case_engine.registry.models import MentalModelDefinition
from case_engine.schemas.base import BaseTrace
from case_engine.schemas.mental_models import SCHEMA_BY_MODEL_ID

__all__ = ["ToolFactory"]

log = get_logger(__name__)


class ToolFactory:
    """Build OpenAI- and Anthropic-style tool specs from registry entries.

    The factory is stateless: every call resolves the registry entry's
    ``schema_class`` against
    :data:`~case_engine.schemas.mental_models.SCHEMA_BY_MODEL_ID` and
    derives the provider payload from the live Pydantic class, so a spec
    can never disagree with the contract the enforcement gate enforces
    moments later.

    Attributes:
        None -- the factory carries no state; it exists as a class so
        provider adapters can subclass and override spec shaping.

    Example:
        >>> factory = ToolFactory()
        >>> reg = CognitiveRegistry.load_default()          # doctest: +SKIP
        >>> spec = factory.openai_tool(reg.get("MM005"))    # doctest: +SKIP
        >>> spec["function"]["name"]                        # doctest: +SKIP
        'RootCauseAnalysisTrace'
    """

    def __init__(self) -> None:
        """Create the factory (stateless; kept as a class for extensibility).

        Side effects:
            Emits a DEBUG ``ToolFactory initialised`` log record; no I/O.
        """
        log.debug("ToolFactory initialised")

    def _schema_class(self, model: MentalModelDefinition) -> type[BaseTrace]:
        """Resolve the contract class for *model*.

        Args:
            model: Registry entry to resolve.

        Returns:
            The Pydantic contract class.

        Raises:
            RegistryError: If ``schema_class`` does not resolve -- a hard
                registry-consistency failure.  Logged at ERROR before
                the raise; the factory refuses to guess or fall back
                (fail-fast: an unresolvable contract must never yield a
                provider spec the gate would then enforce differently).
        """
        log.debug(
            "Resolving schema class",
            extra={"algorithm_id": model.algorithm_id, "expected": model.schema_class},
        )
        cls = SCHEMA_BY_MODEL_ID.get(model.algorithm_id)
        if cls is None or cls.__name__ != model.schema_class:
            log.error(
                "schema_class does not resolve to a registered contract",
                extra={"algorithm_id": model.algorithm_id, "expected": model.schema_class},
            )
            raise RegistryError(
                "schema_class does not resolve to a registered contract",
                algorithm_id=model.algorithm_id,
                expected=model.schema_class,
            )
        return cls

    def json_schema(self, model: MentalModelDefinition) -> dict[str, Any]:
        """Return the JSON Schema for *model*'s contract.

        Useful for docs, diffing against the spec's reference
        ``pydantic_schema`` string, and providers that take raw JSON
        Schema.  The output is generated from the live class, so it is
        always in sync with what the gate validates.

        Args:
            model: Registry entry.

        Returns:
            Draft-2020 JSON Schema dict (Pydantic v2 generator output).

        Raises:
            RegistryError: If the entry's ``schema_class`` does not
                resolve (see :meth:`_schema_class`); logged at ERROR.
        """
        cls = self._schema_class(model)
        log.debug(
            "JSON schema generated",
            extra={"algorithm_id": model.algorithm_id, "tool": cls.__name__},
        )
        return cls.model_json_schema()

    def openai_tool(self, model: MentalModelDefinition) -> dict[str, Any]:
        """Build a Chat-Completions tool spec for *model*.

        The spec embeds the registry's ``description_for_llm`` verbatim
        and the contract's generated JSON Schema as ``parameters``, so
        the provider is constrained by exactly the schema the gate will
        later enforce (``extra="forbid"`` included).

        Args:
            model: Registry entry.

        Returns:
            ``{"type": "function", "function": {name, description,
            parameters}}`` ready for ``tools=[...]``.

        Raises:
            RegistryError: If the entry's ``schema_class`` does not
                resolve (see :meth:`_schema_class`); logged at ERROR.
        """
        cls = self._schema_class(model)
        spec = {
            "type": "function",
            "function": {
                "name": cls.__name__,
                "description": model.description_for_llm,
                "parameters": cls.model_json_schema(),
            },
        }
        log.debug("OpenAI tool spec built", extra={"tool": cls.__name__})
        return spec

    def anthropic_tool(self, model: MentalModelDefinition) -> dict[str, Any]:
        """Build an Anthropic Messages-API tool spec for *model*.

        Same content as the OpenAI shape, re-keyed for the Messages API
        (``input_schema`` instead of nested ``function.parameters``).

        Args:
            model: Registry entry.

        Returns:
            ``{"name", "description", "input_schema"}`` ready for
            ``tools=[...]``.

        Raises:
            RegistryError: If the entry's ``schema_class`` does not
                resolve (see :meth:`_schema_class`); logged at ERROR.
        """
        cls = self._schema_class(model)
        spec = {
            "name": cls.__name__,
            "description": model.description_for_llm,
            "input_schema": cls.model_json_schema(),
        }
        log.debug("Anthropic tool spec built", extra={"tool": cls.__name__})
        return spec

    def generic_tool(self, model: MentalModelDefinition) -> dict[str, Any]:
        """Build the canonical (OpenAI-shaped) spec used inside pipeline state.

        The pipeline stores OpenAI-shaped specs in ``CASEState.tool_specs``
        because they are JSON-serializable and provider adapters convert
        as needed.  Alias for :meth:`openai_tool` kept explicit so call
        sites read honestly about their intent.

        Args:
            model: Registry entry.

        Returns:
            OpenAI-shaped tool spec dict.

        Raises:
            RegistryError: If the entry's ``schema_class`` does not
                resolve (see :meth:`_schema_class`); logged at ERROR.
        """
        log.debug(
            "Generic (pipeline-state) tool spec requested",
            extra={"algorithm_id": model.algorithm_id},
        )
        return self.openai_tool(model)
